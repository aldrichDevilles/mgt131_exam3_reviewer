document.addEventListener('DOMContentLoaded', () => {
    Object.keys(quizData).forEach(modKey => {
        const form = document.querySelector(`form[data-module="${modKey}"]`);
        if (!form) return;

        const wrapper = form.querySelector('.questions-wrapper');
        const resultsContainer = form.nextElementSibling;
        const moduleQuestions = quizData[modKey];

        // 1. Render Questions
        moduleQuestions.forEach((q, index) => {
            const qBlock = document.createElement('div');
            qBlock.className = 'question-block';

            const qText = document.createElement('div');
            qText.className = 'question-text';
            qText.textContent = `${index + 1}. ${q.q}`;
            qBlock.appendChild(qText);

            const optionsGrid = document.createElement('div');
            optionsGrid.className = 'options-grid';

            q.opts.forEach(opt => {
                const label = document.createElement('label');
                label.className = 'option-label';

                const input = document.createElement('input');
                input.type = 'radio';
                input.name = `q-${q.id}`;
                input.value = opt;

                const span = document.createElement('span');
                span.textContent = opt;

                label.appendChild(input);
                label.appendChild(span);
                optionsGrid.appendChild(label);
            });
            qBlock.appendChild(optionsGrid);

            // "View Answer" Button
            const viewAnswerBtn = document.createElement('button');
            viewAnswerBtn.type = 'button';
            viewAnswerBtn.className = 'btn view-answer-btn';
            viewAnswerBtn.textContent = 'View Answer';

            const revealDiv = document.createElement('div');
            revealDiv.className = 'answer-reveal hidden';

            viewAnswerBtn.addEventListener('click', () => {
                const checkedInput = qBlock.querySelector(`input[name="q-${q.id}"]:checked`);
                const userAnswer = checkedInput ? checkedInput.value : 'No answer selected';
                const isCorrect = userAnswer === q.a;

                revealDiv.innerHTML = `
                    <div class="${isCorrect ? 'review-correct' : 'review-incorrect'}" style="padding-left: 10px;">
                        <p style="margin-bottom: 5px;">Your Answer: <span class="${isCorrect ? 'correct-text' : 'incorrect-text'}">${userAnswer} ${isCorrect ? '✔' : '✘'}</span></p>
                        ${!isCorrect ? `<div class="real-answer">Correct Answer: ${q.a}</div>` : ''}
                    </div>
                `;
                revealDiv.classList.remove('hidden');
                viewAnswerBtn.classList.add('hidden');
            });

            qBlock.appendChild(viewAnswerBtn);
            qBlock.appendChild(revealDiv);
            wrapper.appendChild(qBlock);
        });

        // 2. Form Submit Logic
        form.addEventListener('submit', (e) => {
            e.preventDefault();

            let correctCount = 0;
            const formData = new FormData(form);
            const answers = Object.fromEntries(formData.entries());

            let reviewItemsHTML = '';
            moduleQuestions.forEach((q, idx) => {
                const userAnswer = answers[`q-${q.id}`];
                const isCorrect = userAnswer === q.a;
                if (isCorrect) correctCount++;

                reviewItemsHTML += `
                    <div class="answer-reveal ${isCorrect ? 'review-correct' : 'review-incorrect'}" style="display: block;">
                        <p><strong>${idx + 1}. ${q.q}</strong></p>
                        <p>Your Answer: <span class="${isCorrect ? 'correct-text' : 'incorrect-text'}">${userAnswer || 'Skipped'} ${isCorrect ? '✔' : '✘'}</span></p>
                        ${!isCorrect ? `<div class="real-answer">Correct Answer: ${q.a}</div>` : ''}
                    </div>
                `;
            });

            resultsContainer.innerHTML = `
                <div class="card" style="text-align: center; margin-bottom: 20px;">
                    <h2>Module Score: <span style="color: var(--primary);">${correctCount}</span> / ${moduleQuestions.length}</h2>
                    <button type="button" class="btn submit-btn retry-btn" style="width: auto; padding: 10px 24px;">Retake Quiz</button>
                </div>
                <h3>Detailed Review:</h3>
                ${reviewItemsHTML}
            `;

            resultsContainer.querySelector('.retry-btn').addEventListener('click', () => {
                form.reset();
                wrapper.querySelectorAll('.view-answer-btn').forEach(btn => btn.classList.remove('hidden'));
                wrapper.querySelectorAll('.answer-reveal').forEach(div => {
                    div.classList.add('hidden');
                    div.innerHTML = '';
                });
                resultsContainer.classList.add('hidden');
                form.classList.remove('hidden');
                document.getElementById(`section-${modKey}`).scrollIntoView({ behavior: 'smooth' });
            });

            form.classList.add('hidden');
            resultsContainer.classList.remove('hidden');
            document.getElementById(`section-${modKey}`).scrollIntoView({ behavior: 'smooth' });
        });
    });
});